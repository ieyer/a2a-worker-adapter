def _env_bool(name: str, default: bool = False) -> bool:
    value = os.getenv(name)
    if value is None:
        return default
    return value.strip().lower() in {"1", "true", "yes", "on"}


def _task_state_name(state: TaskState) -> str:
    """Human-readable name for a protobuf TaskState value (for hooks/logs)."""
    try:
        return TaskState.Name(state)  # type: ignore[attr-defined]
    except Exception:
        return str(state)


def _sha256_json(value: dict[str, Any]) -> str:
    raw = json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()


# v2.2.1: fields generated by the A2A transport layer. They change on every
# server-side Task creation (new Task UUID) and must be excluded from the
# persistent idempotency payload hash, so replaying the same stable message_id
# with the same business envelope returns the cached result instead of
# IDEMPOTENCY_CONFLICT.
TRANSPORT_HASH_EXCLUDE = frozenset({"a2a_task_id"})


def _idempotency_payload_hash(envelope: dict[str, Any]) -> str:
    business = {k: v for k, v in envelope.items() if k not in TRANSPORT_HASH_EXCLUDE}
    return _sha256_json(business)


@dataclass(slots=True)
class RuntimeResult:
    ok: bool
    text: str
    details: dict[str, Any]


@dataclass(slots=True)
class StoredResult:
    payload_hash: str
    result: RuntimeResult


class IdempotencyStore:
    """Small persistent result store. Same messageId never executes twice after a result exists."""

    def __init__(self, path: str | None) -> None:
        self.path = Path(path) if path else None
        if self.path:
            self.path.parent.mkdir(parents=True, exist_ok=True)
            self._init_db()

    def _connect(self) -> sqlite3.Connection:
        assert self.path is not None
        conn = sqlite3.connect(self.path, timeout=10)
        conn.execute("PRAGMA journal_mode=WAL")
        conn.execute("PRAGMA synchronous=NORMAL")
        return conn

    def _init_db(self) -> None:
        with self._connect() as conn:
            conn.execute(
                """
                CREATE TABLE IF NOT EXISTS a2a_results (
                    worker_id TEXT NOT NULL,
                    message_id TEXT NOT NULL,
                    payload_hash TEXT NOT NULL,
                    ok INTEGER NOT NULL,
                    text TEXT NOT NULL,
                    details_json TEXT NOT NULL,
                    created_at REAL NOT NULL,
                    PRIMARY KEY(worker_id, message_id)
                )
                """
            )

    async def get(self, message_id: str) -> StoredResult | None:
        if not self.path:
            return None
        return await asyncio.to_thread(self._get_sync, message_id)

    def _get_sync(self, message_id: str) -> StoredResult | None:
        with self._connect() as conn:
            row = conn.execute(
                "SELECT payload_hash, ok, text, details_json FROM a2a_results WHERE worker_id=? AND message_id=?",
                (WORKER_ID, message_id),
            ).fetchone()
        if not row:
            return None
        payload_hash, ok, text, details_json = row
        try:
            details = json.loads(details_json)
        except json.JSONDecodeError:
            details = {"code": "CORRUPT_STORED_DETAILS"}
        return StoredResult(payload_hash, RuntimeResult(bool(ok), text, details))

    async def put(self, message_id: str, payload_hash: str, result: RuntimeResult) -> None:
        if not self.path:
            return
        await asyncio.to_thread(self._put_sync, message_id, payload_hash, result)

    def _put_sync(self, message_id: str, payload_hash: str, result: RuntimeResult) -> None:
        with self._connect() as conn:
            conn.execute(
                """
                INSERT OR REPLACE INTO a2a_results
                (worker_id, message_id, payload_hash, ok, text, details_json, created_at)
                VALUES (?, ?, ?, ?, ?, ?, ?)
                """,
                (
                    WORKER_ID,
                    message_id,
                    payload_hash,
                    1 if result.ok else 0,
                    result.text,
                    json.dumps(result.details, ensure_ascii=False, sort_keys=True),
                    time.time(),
                ),
            )


class WorkerRuntimeBridge:
    """Translate an A2A task into a local worker runtime invocation."""

    def __init__(
        self,
        *,
        mode: str = "disabled",
        command: str | None = None,
        url: str | None = None,
        token: str | None = None,
        timeout: float = 300.0,
        spool_dir: str | None = None,
        allow_remote_http: bool = False,
    ) -> None:
        self.mode = mode.strip().lower()
        self.command = command
        self.url = url
        self.token = token
        self.timeout = timeout
        self.spool_dir = spool_dir
        self.allow_remote_http = allow_remote_http
        if self.mode not in {"disabled", "command", "http", "spool"}:
            raise ValueError(f"Unsupported WORKER_WAKE_MODE: {self.mode}")
        if self.mode == "http" and self.url:
            self._validate_http_url(self.url)

    @classmethod
    def from_env(cls) -> "WorkerRuntimeBridge":
        return cls(
            mode=os.getenv("WORKER_WAKE_MODE", "disabled"),
            command=os.getenv("WORKER_WAKE_COMMAND"),
            url=os.getenv("WORKER_WAKE_URL"),
            token=os.getenv("WORKER_WAKE_TOKEN"),
            timeout=float(os.getenv("WORKER_WAKE_TIMEOUT", "300")),
            spool_dir=os.getenv("WORKER_SPOOL_DIR"),
            allow_remote_http=_env_bool("WORKER_WAKE_ALLOW_REMOTE_HTTP", False),
        )

    def _validate_http_url(self, url: str) -> None:
        parsed = urlparse(url)
        if parsed.scheme not in {"http", "https"} or not parsed.hostname:
            raise ValueError("WORKER_WAKE_URL must be an http(s) URL")
        if self.allow_remote_http:
            return
        if parsed.hostname not in {"127.0.0.1", "localhost", "::1"}:
            raise ValueError(
                "WORKER_WAKE_URL must be loopback by default. Set WORKER_WAKE_ALLOW_REMOTE_HTTP=true only for a trusted private endpoint."
            )

    def describe(self) -> dict[str, Any]:
        return {
            "mode": self.mode,
            "configured": self.is_configured(),
            "timeout_seconds": self.timeout,
        }

    def is_configured(self) -> bool:
        if self.mode == "command":
            return bool(self.command)
        if self.mode == "http":
            return bool(self.url)
        if self.mode == "spool":
            return bool(self.spool_dir)
        return False

    async def invoke(self, payload: dict[str, Any]) -> RuntimeResult:
        if self.mode == "command":
            return await self._invoke_command(payload)
        if self.mode == "http":
            return await self._invoke_http(payload)
        if self.mode == "spool":
            return await self._invoke_spool(payload)
        return RuntimeResult(
            ok=False,
            text=f"{WORKER_ID} runtime wake is not configured.",
            details={"code": "REAL_WAKE_PENDING", "mode": self.mode},
        )

    async def _invoke_command(self, payload: dict[str, Any]) -> RuntimeResult:
        if not self.command:
            return RuntimeResult(False, "WORKER_WAKE_COMMAND is missing.", {"code": "CONFIG_ERROR"})
        argv = shlex.split(self.command)
        if not argv:
            return RuntimeResult(False, "WORKER_WAKE_COMMAND is empty.", {"code": "CONFIG_ERROR"})
        proc = await asyncio.create_subprocess_exec(
            *argv,
            stdin=asyncio.subprocess.PIPE,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
        )
        try:
            stdout, stderr = await asyncio.wait_for(
                proc.communicate(json.dumps(payload, ensure_ascii=False).encode("utf-8")),
                timeout=self.timeout,
            )
        except TimeoutError:
            proc.kill()
            await proc.wait()
            return RuntimeResult(False, f"{WORKER_ID} command bridge timed out.", {"code": "TIMEOUT"})
        out_text = stdout.decode("utf-8", errors="replace").strip()
        err_text = stderr.decode("utf-8", errors="replace").strip()
        if proc.returncode != 0:
            return RuntimeResult(
                False,
                err_text or out_text or f"Worker command exited with {proc.returncode}.",
                {"code": "COMMAND_FAILED", "returncode": proc.returncode},
            )
        return _runtime_result_from_body(out_text, {"returncode": proc.returncode, "mode": "command"})

    async def _invoke_http(self, payload: dict[str, Any]) -> RuntimeResult:
        if not self.url:
            return RuntimeResult(False, "WORKER_WAKE_URL is missing.", {"code": "CONFIG_ERROR"})
        headers = {"content-type": "application/json"}
        if self.token:
            headers["authorization"] = f"Bearer {self.token}"
        try:
            async with httpx.AsyncClient(timeout=self.timeout, headers=headers, follow_redirects=False) as client:
                response = await client.post(self.url, json=payload)
        except Exception as exc:
            return RuntimeResult(False, f"Worker HTTP bridge failed: {exc}", {"code": "HTTP_ERROR"})
        body = response.text.strip()
        if response.status_code >= 400:
            return RuntimeResult(
                False,
                body or f"Worker HTTP bridge returned {response.status_code}.",
                {"code": "HTTP_STATUS", "status_code": response.status_code},
            )
        return _runtime_result_from_body(body, {"status_code": response.status_code, "mode": "http"})

    async def _invoke_spool(self, payload: dict[str, Any]) -> RuntimeResult:
        if not self.spool_dir:
            return RuntimeResult(False, "WORKER_SPOOL_DIR is missing.", {"code": "CONFIG_ERROR"})
        root = Path(self.spool_dir)
        inbox = root / "inbox"
        outbox = root / "outbox"
        inbox.mkdir(parents=True, exist_ok=True)
        outbox.mkdir(parents=True, exist_ok=True)
        stable_key = str(payload.get("message_id") or payload.get("task_id") or _sha256_json(payload))
        file_key = hashlib.sha256(stable_key.encode("utf-8")).hexdigest()[:32]
        request_path = inbox / f"{file_key}.json"
        response_path = outbox / f"{file_key}.json"
        temp_path = inbox / f".{file_key}.tmp"
        payload_with_hash = dict(payload)
        payload_with_hash["payload_hash"] = _sha256_json(payload)
        await asyncio.to_thread(
            temp_path.write_text,
            json.dumps(payload_with_hash, ensure_ascii=False, indent=2),
            "utf-8",
        )
        await asyncio.to_thread(os.replace, temp_path, request_path)
        deadline = asyncio.get_running_loop().time() + self.timeout
        while asyncio.get_running_loop().time() < deadline:
            if response_path.exists():
                body = await asyncio.to_thread(response_path.read_text, "utf-8")
                try:
                    await asyncio.to_thread(response_path.unlink)
                except FileNotFoundError:
                    pass
                return _runtime_result_from_body(body, {"mode": "spool"})
            await asyncio.sleep(0.25)
        return RuntimeResult(
            False,
            "Worker spool request was written but no runtime response arrived before timeout.",
            {"code": "SPOOL_TIMEOUT", "request_file": str(request_path)},
        )


def _runtime_result_from_body(body: str, extra: dict[str, Any] | None = None) -> RuntimeResult:
    details = dict(extra or {})
    if not body:
        return RuntimeResult(True, "Worker runtime accepted the task.", details)
    try:
        data = json.loads(body)
    except json.JSONDecodeError:
        return RuntimeResult(True, body, details)
    if isinstance(data, dict):
        if "ok" in data:
            ok = bool(data["ok"])
        else:
            ok = not bool(data.get("error")) and str(data.get("status", "")).lower() not in {"error", "failed", "failure"}
        text = str(
            data.get("output")
            or data.get("text")
            or data.get("message")
            or data.get("error")
            or ("Worker runtime completed." if ok else "Worker runtime failed.")
        )
        for key in ("run_id", "status", "code"):
            if key in data:
                details[key] = data[key]
        return RuntimeResult(ok, text, details)
    return RuntimeResult(True, body, details)


def parse_task_envelope(raw_text: str, max_message_bytes: int = 262_144) -> dict[str, Any]:
    if len(raw_text.encode("utf-8")) > max_message_bytes:
        raise ValueError(f"Task message exceeds A2A_MAX_MESSAGE_BYTES={max_message_bytes}.")
    text = raw_text.strip()
    if not text:
        return {"worker_id": WORKER_ID, "message": ""}
    try:
        value = json.loads(text)
    except json.JSONDecodeError:
        return {"worker_id": WORKER_ID, "message": text}
    if not isinstance(value, dict):
        return {"worker_id": WORKER_ID, "message": text}
    worker_id = value.get("worker_id") or WORKER_ID
    if worker_id != WORKER_ID:
        raise ValueError(f"Task is assigned to {worker_id}, not {WORKER_ID}.")
    value["worker_id"] = WORKER_ID
    return value


def _public_result_details(details: dict[str, Any], *, cached: bool) -> dict[str, Any]:
    safe = {"cached": cached}
    for key in ("code", "mode", "returncode", "status_code", "run_id", "status"):
        if key in details:
            safe[key] = details[key]
    return safe


class WorkerAdapterExecutor(AgentExecutor):
    """Execute A2A tasks through a real worker runtime bridge with persistent idempotency."""

    def __init__(
        self,
        bridge: WorkerRuntimeBridge,
        *,
        result_store: IdempotencyStore | None = None,
        max_message_bytes: int = 262_144,
    ) -> None:
        self.bridge = bridge
        self.result_store = result_store or IdempotencyStore(None)
        self.max_message_bytes = max_message_bytes
        self._inflight: dict[str, asyncio.Future[RuntimeResult]] = {}
        self._inflight_lock = asyncio.Lock()

    async def _execute_once(
        self,
        message_id: str,
        payload_hash: str,
        envelope: dict[str, Any],
    ) -> tuple[RuntimeResult, bool]:
        stored = await self.result_store.get(message_id)
        if stored:
            if stored.payload_hash != payload_hash:
                return RuntimeResult(
                    False,
                    "messageId was already used with a different payload.",
                    {"code": "IDEMPOTENCY_CONFLICT"},
                ), True
            return stored.result, True

        owner = False
        async with self._inflight_lock:
            future = self._inflight.get(message_id)
            if future is None:
                future = asyncio.get_running_loop().create_future()
                self._inflight[message_id] = future
                owner = True

        if not owner:
            result = await future
            return result, True

        try:
            await hooks.emit("before_dispatch", envelope=envelope)
            result = await self.bridge.invoke(envelope)
            await hooks.emit("after_dispatch", envelope=envelope, result=result)
            await self.result_store.put(message_id, payload_hash, result)
            future.set_result(result)
            return result, False
        except Exception as exc:
            result = RuntimeResult(False, f"Worker adapter internal error: {exc}", {"code": "ADAPTER_INTERNAL_ERROR"})
            await self.result_store.put(message_id, payload_hash, result)
            future.set_result(result)
            return result, False
        finally:
            async with self._inflight_lock:
                self._inflight.pop(message_id, None)

    async def execute(self, context: RequestContext, event_queue: EventQueue) -> None:
        task = context.current_task or new_task_from_user_message(context.message)
        await event_queue.enqueue_event(task)
        await hooks.emit("on_task_created", task_id=task.id, context_id=task.context_id)
        raw_text = get_message_text(context.message)
        try:
            envelope = parse_task_envelope(raw_text, self.max_message_bytes)
        except ValueError as exc:
            await event_queue.enqueue_event(
                new_text_status_update_event(
                    task_id=task.id,
                    context_id=task.context_id,
                    state=TaskState.TASK_STATE_REJECTED,
                    text=str(exc),
                )
            )
            return

        await hooks.emit("on_message_received", envelope=dict(envelope), task_id=task.id)

        message_id = getattr(context.message, "message_id", "") or task.id
        envelope.setdefault("task_id", task.id)
        envelope.setdefault("a2a_task_id", task.id)
        envelope["message_id"] = message_id
        envelope["worker_id"] = WORKER_ID
        # v2.2.1 hotfix: hash the business envelope only; the server-generated
        # a2a_task_id transport UUID is excluded so a replay that arrives as a
        # new A2A Task still hits the cached result.
        payload_hash = _idempotency_payload_hash(envelope)

        await event_queue.enqueue_event(
            new_text_status_update_event(
                task_id=task.id,
                context_id=task.context_id,
                state=TaskState.TASK_STATE_WORKING,
                text=f"{WORKER_ID} adapter accepted the task and is invoking the runtime.",
            )
        )
        await hooks.emit(
            "on_task_state_changed",
            task_id=task.id,
            state=_task_state_name(TaskState.TASK_STATE_WORKING),
            cached=False,
        )

        result, cached = await self._execute_once(message_id, payload_hash, envelope)
        public_details = _public_result_details(result.details, cached=cached)
        artifact_text = result.text
        if public_details:
            artifact_text += "\n\nadapter_metadata=" + json.dumps(public_details, ensure_ascii=False, sort_keys=True)
        await event_queue.enqueue_event(
            new_text_artifact_update_event(
                task_id=task.id,
                context_id=task.context_id,
                name=f"{WORKER_ID.lower()}_dispatch_receipt",
                text=artifact_text,
            )
        )
        final_state = TaskState.TASK_STATE_COMPLETED if result.ok else TaskState.TASK_STATE_FAILED
        final_text = (
            f"{WORKER_ID} A2A dispatch/wake completed; business execution remains authoritative in the caller's task ledger."
            if result.ok
            else f"{WORKER_ID} A2A dispatch/wake failed."
        )
        await event_queue.enqueue_event(
            new_text_status_update_event(
                task_id=task.id,
                context_id=task.context_id,
                state=final_state,
                text=final_text,
            )
        )
        await hooks.emit(
            "on_task_state_changed",
            task_id=task.id,
            state=_task_state_name(final_state),
            cached=cached,
        )
        if final_state == TaskState.TASK_STATE_COMPLETED:
            await hooks.emit(
                "on_task_completed",
                task_id=task.id,
                ok=result.ok,
                details=public_details,
            )

    async def cancel(self, context: RequestContext, event_queue: EventQueue) -> None:
        task: Task | None = context.current_task
        if task is None:
            return
        await event_queue.enqueue_event(
            new_text_status_update_event(
                task_id=task.id,
                context_id=task.context_id,
                state=TaskState.TASK_STATE_CANCELED,
                text=f"{WORKER_ID} adapter task canceled.",
            )
        )



class BearerAuthMiddleware(BaseHTTPMiddleware):
    def __init__(self, app, *, token: str | None, allow_unauthenticated: bool) -> None:
        super().__init__(app)
        self.token = token
        self.allow_unauthenticated = allow_unauthenticated

    async def dispatch(self, request: Request, call_next):
        if request.url.path in {"/.well-known/agent-card.json", "/healthz"}:
            return await call_next(request)
        if self.allow_unauthenticated:
            return await call_next(request)
        if not self.token:
            return JSONResponse(
                {"error": "server authentication is not configured"},
                status_code=503,
                headers={"Cache-Control": "no-store"},
            )
        supplied = request.headers.get("authorization", "")
        expected = f"Bearer {self.token}"
        if not secrets.compare_digest(supplied, expected):
            return JSONResponse(
                {"error": "unauthorized"},
                status_code=401,
                headers={"WWW-Authenticate": "Bearer", "Cache-Control": "no-store"},
            )
        return await call_next(request)


def make_agent_card(agent_url: str, *, auth_required: bool = True) -> AgentCard:
    skill = AgentSkill(
        id="dispatch_assigned_task",
        name="Dispatch and wake an assigned worker task",
        description=(
            f"Accepts a task envelope for {WORKER_ID}, wakes the configured local runtime, and returns a dispatch receipt. "
            "A real wake capability is reported only when a command, HTTP hook, or spool consumer is configured."
        ),
        tags=["worker", "task", "adapter", "runtime"],
        examples=["status check", json.dumps({"task_id": "T-123", "worker_id": WORKER_ID, "message": "run the task"})],
        input_modes=["text/plain"],
        output_modes=["text/plain"],
    )
    kwargs: dict[str, Any] = {}
    if auth_required:
        kwargs["security_schemes"] = {
            "bearerAuth": SecurityScheme(
                http_auth_security_scheme=HTTPAuthSecurityScheme(
                    description="Bearer token required for A2A task execution.",
                    scheme="Bearer",
                    bearer_format="opaque",
                )
            )
        }
        kwargs["security_requirements"] = [
            SecurityRequirement(schemes={"bearerAuth": StringList(list=[])})
        ]
    return AgentCard(
        name=AGENT_NAME,
        description=f"A2A 1.0 adapter for {WORKER_ID} with authenticated command, HTTP, or spool runtime wake bridges.",
        supported_interfaces=[
            AgentInterface(protocol_binding="JSONRPC", url=agent_url, protocol_version="1.0")
        ],
        version=ADAPTER_VERSION,
        capabilities=AgentCapabilities(streaming=True),
        default_input_modes=["text/plain"],
        default_output_modes=["text/plain"],
        skills=[skill],
        **kwargs,
    )


def create_app(
    agent_url: str = f"http://{DEFAULT_HOST}:{DEFAULT_PORT}/",
    *,
    bridge: WorkerRuntimeBridge | None = None,
    bearer_token: str | None = None,
    allow_unauthenticated: bool = False,
    idempotency_db: str | None = None,
    max_message_bytes: int = 262_144,
) -> Starlette:
    bridge = bridge or WorkerRuntimeBridge.from_env()
    idempotency_db = idempotency_db or os.getenv(
        "A2A_IDEMPOTENCY_DB", f"./data/{WORKER_ID.lower()}-a2a-idempotency.sqlite3"
    )
    result_store = IdempotencyStore(idempotency_db)
    card = make_agent_card(agent_url, auth_required=not allow_unauthenticated)
    request_handler = DefaultRequestHandler(
        agent_executor=WorkerAdapterExecutor(
            bridge,
            result_store=result_store,
            max_message_bytes=max_message_bytes,
        ),
        task_store=InMemoryTaskStore(),
        agent_card=card,
    )
    routes = create_agent_card_routes(card, cache_control="public, max-age=60")
    routes.extend(create_jsonrpc_routes(request_handler, rpc_url="/"))

    async def healthz(request: Request) -> JSONResponse:
        return JSONResponse(
            {
                "ok": True,
                "worker_id": WORKER_ID,
                "a2a_version": "1.0",
                "adapter_version": ADAPTER_VERSION,
                "runtime_bridge": bridge.describe(),
                "auth_required": not allow_unauthenticated,
                "idempotency_persistent": bool(idempotency_db),
            }
        )

    routes.append(Route("/healthz", healthz, methods=["GET"]))

    @asynccontextmanager
    async def lifespan(app: Starlette):
        yield
        close = getattr(request_handler, "aclose", None)
        if close:
            await close()

    app = Starlette(routes=routes, lifespan=lifespan)
    app.add_middleware(
        BearerAuthMiddleware,
        token=bearer_token,
        allow_unauthenticated=allow_unauthenticated,
    )
    app.state.agent_card = card
    app.state.runtime_bridge = bridge
    app.state.idempotency_store = result_store
    return app


def main() -> None:
    parser = argparse.ArgumentParser(description="Run the reusable A2A worker runtime adapter.")
    parser.add_argument("--host", default=os.getenv("A2A_HOST", DEFAULT_HOST))
    parser.add_argument("--port", type=int, default=int(os.getenv("A2A_PORT", str(DEFAULT_PORT))))
    parser.add_argument("--agent-url", default=os.getenv("A2A_AGENT_URL"))
    parser.add_argument("--bearer-token", default=os.getenv("A2A_BEARER_TOKEN"))
    parser.add_argument(
        "--allow-unauthenticated",
        action="store_true",
        default=_env_bool("A2A_ALLOW_UNAUTHENTICATED", False),
        help="Explicit demo-only escape hatch. Do not use for production task execution.",
    )
    parser.add_argument(
        "--wake-mode",
        choices=["disabled", "command", "http", "spool"],
        default=os.getenv("WORKER_WAKE_MODE", "disabled"),
    )
    parser.add_argument("--wake-command", default=os.getenv("WORKER_WAKE_COMMAND"))
    parser.add_argument("--wake-url", default=os.getenv("WORKER_WAKE_URL"))
    parser.add_argument("--wake-token", default=os.getenv("WORKER_WAKE_TOKEN"))
    parser.add_argument(
        "--wake-timeout",
        type=float,
        default=float(os.getenv("WORKER_WAKE_TIMEOUT", "300")),
    )
    parser.add_argument("--spool-dir", default=os.getenv("WORKER_SPOOL_DIR"))
    parser.add_argument(
        "--idempotency-db",
        default=os.getenv("A2A_IDEMPOTENCY_DB", f"./data/{WORKER_ID.lower()}-a2a-idempotency.sqlite3"),
    )
    parser.add_argument(
        "--max-message-bytes",
        type=int,
        default=int(os.getenv("A2A_MAX_MESSAGE_BYTES", "262144")),
    )
    args = parser.parse_args()

    hooks.load_from_env()

    if not args.allow_unauthenticated and not args.bearer_token:
        parser.error("A2A_BEARER_TOKEN is required unless --allow-unauthenticated is explicitly set for demo use.")

    bridge = WorkerRuntimeBridge(
        mode=args.wake_mode,
        command=args.wake_command,
        url=args.wake_url,
        token=args.wake_token,
        timeout=args.wake_timeout,
        spool_dir=args.spool_dir,
        allow_remote_http=_env_bool("WORKER_WAKE_ALLOW_REMOTE_HTTP", False),
    )
    agent_url = args.agent_url or f"http://127.0.0.1:{args.port}/"
    app = create_app(
        agent_url,
        bridge=bridge,
        bearer_token=args.bearer_token,
        allow_unauthenticated=args.allow_unauthenticated,
        idempotency_db=args.idempotency_db,
        max_message_bytes=args.max_message_bytes,
    )
    uvicorn.run(app, host=args.host, port=args.port, log_level="info")


if __name__ == "__main__":
    main()
